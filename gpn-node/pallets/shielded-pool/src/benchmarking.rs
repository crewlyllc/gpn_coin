/// `fee = 2` encoded as the pallet's on-chain parser expects (`b[0..8]` u64 BE).
fn fee2_input() -> [u8; 32] {
    let mut out = [0u8; 32];
    out[7] = 2;
    out
}

/// Fund `caller` with half the max balance so its deposit transfer succeeds
/// regardless of the runtime's existential deposit / fee constants.
fn fund<T: Config>(caller: &T::AccountId) {
    T::Currency::make_free_balance_be(caller, BalanceOf::<T>::max_value() / 2u32.into());
}

#[benchmarks]
mod benchmarks {
    use super::*;

    #[benchmark]
    fn verify_proof() {
        let caller: T::AccountId = whitelisted_caller();
        let public_inputs = sp_std::vec![fee2_input()];

        #[extrinsic_call]
        verify_proof(
            RawOrigin::Signed(caller.clone()),
            REAL_A,
            REAL_B,
            REAL_C,
            public_inputs,
        );
    }

    #[benchmark]
    fn deposit() {
        let caller: T::AccountId = whitelisted_caller();
        fund::<T>(&caller);
        let amount: BalanceOf<T> = 500u32.into();
        let addr: [u8; 32] = [7u8; 32];
        let nonce: u64 = 0;

        #[extrinsic_call]
        deposit(RawOrigin::Signed(caller), amount, addr, nonce);

        assert_eq!(ShieldedPool::<T>::pool_size(), 1);
    }

    impl_benchmark_test_suite!(
        ShieldedPool,
        crate::tests::new_test_ext(),
        crate::tests::Test
    );
}
